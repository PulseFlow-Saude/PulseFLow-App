/// Exibe o nome do país conforme o idioma da UI; [canonicalEnglish] é sempre o valor da lista ISO em inglês.
String nationalityDisplayLabel(String canonicalEnglish, {required bool usePortuguese}) {
  if (!usePortuguese) return canonicalEnglish;
  return kNationalityEnglishToPortugueseBr[canonicalEnglish] ?? canonicalEnglish;
}

/// Garante que todo país da lista tenha rótulo PT (executar em testes ou modo debug).
bool nationalityPortugueseLabelsCoverList() {
  for (final n in kWorldNationalities) {
    if (!kNationalityEnglishToPortugueseBr.containsKey(n)) return false;
  }
  return true;
}
